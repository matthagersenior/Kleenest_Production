create or replace function internal.owner_email_center_provider_config()
returns jsonb
language plpgsql
security definer
set search_path=''
as $$
declare
  v_key text;
  v_from text;
  v_webhook text;
begin
  if coalesce(auth.jwt()->>'role','') <> 'service_role' then
    raise exception 'Service role required';
  end if;
  select decrypted_secret into v_key
  from vault.decrypted_secrets
  where name='owner_email_resend_api_key'
  limit 1;
  select decrypted_secret into v_from
  from vault.decrypted_secrets
  where name='owner_email_from_address'
  limit 1;
  select decrypted_secret into v_webhook
  from vault.decrypted_secrets
  where name='owner_email_webhook_secret'
  limit 1;
  return jsonb_build_object(
    'provider','resend',
    'api_key',coalesce(v_key,''),
    'configured',coalesce(length(v_key),0)>0,
    'from_address',coalesce(v_from,'Kleenest Owner <onboarding@resend.dev>'),
    'webhook_secret',coalesce(v_webhook,''),
    'webhook_configured',coalesce(length(v_webhook),0)>0
  );
end
$$;

revoke all on function internal.owner_email_center_provider_config() from public,anon,authenticated;
grant execute on function internal.owner_email_center_provider_config() to service_role;

create or replace function internal.owner_email_center_status_snapshot(p_owner_user_id uuid)
returns jsonb
language sql
security definer
set search_path=''
as $$
  select jsonb_build_object(
    'threads_total',(select count(*) from public.owner_email_center_threads where owner_user_id=p_owner_user_id),
    'unread_total',(select count(*) from public.owner_email_center_threads where owner_user_id=p_owner_user_id and unread),
    'needs_reply_total',(select count(*) from public.owner_email_center_threads where owner_user_id=p_owner_user_id and folder='inbox' and latest_direction='inbound'),
    'waiting_total',(select count(*) from public.owner_email_center_threads where owner_user_id=p_owner_user_id and folder<>'trash' and latest_direction='outbound')
  )
$$;

revoke all on function internal.owner_email_center_status_snapshot(uuid) from public,anon,authenticated;
grant execute on function internal.owner_email_center_status_snapshot(uuid) to service_role;

