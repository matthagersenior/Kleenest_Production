create table if not exists public.owner_email_center_settings (
  owner_user_id uuid primary key references auth.users(id) on delete cascade,
  inbox_address text not null default 'support@kleenest.us',
  fallback_email text,
  from_name text not null default 'Kleenest',
  provider text not null default 'resend',
  provider_domain_id text,
  domain_status text not null default 'pending' check (domain_status in ('pending','verified','failed')),
  webhook_enabled boolean not null default false,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.owner_email_center_threads (
  id uuid primary key default gen_random_uuid(),
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  subject text not null default '(no subject)',
  normalized_subject text not null default '',
  folder text not null default 'inbox' check (folder in ('inbox','archive','sent','trash')),
  unread boolean not null default true,
  starred boolean not null default false,
  priority text not null default 'normal' check (priority in ('low','normal','high','urgent')),
  labels text[] not null default '{}',
  participants text[] not null default '{}',
  snippet text not null default '',
  latest_direction text not null default 'inbound' check (latest_direction in ('inbound','outbound')),
  message_count integer not null default 0 check (message_count >= 0),
  has_attachment boolean not null default false,
  last_message_at timestamptz not null default now(),
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.owner_email_center_messages (
  id uuid primary key default gen_random_uuid(),
  thread_id uuid not null references public.owner_email_center_threads(id) on delete cascade,
  owner_user_id uuid not null references auth.users(id) on delete cascade,
  provider_email_id text unique,
  internet_message_id text unique,
  in_reply_to text,
  reference_ids text[] not null default '{}',
  direction text not null check (direction in ('inbound','outbound')),
  from_address text not null,
  from_name text,
  to_addresses text[] not null default '{}',
  cc_addresses text[] not null default '{}',
  bcc_addresses text[] not null default '{}',
  subject text not null default '(no subject)',
  text_body text not null default '',
  html_body text,
  headers jsonb not null default '{}'::jsonb,
  attachments jsonb not null default '[]'::jsonb,
  delivery_status text not null default 'received',
  received_at timestamptz,
  sent_at timestamptz,
  created_at timestamptz not null default now()
);

create table if not exists public.owner_email_center_audit (
  id bigint generated by default as identity primary key,
  owner_user_id uuid references auth.users(id) on delete set null,
  thread_id uuid references public.owner_email_center_threads(id) on delete set null,
  action text not null,
  detail jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create index if not exists owner_email_center_threads_owner_folder_last_idx
  on public.owner_email_center_threads(owner_user_id,folder,last_message_at desc);
create index if not exists owner_email_center_threads_owner_unread_idx
  on public.owner_email_center_threads(owner_user_id,unread,last_message_at desc);
create index if not exists owner_email_center_messages_thread_created_idx
  on public.owner_email_center_messages(thread_id,created_at);
create index if not exists owner_email_center_messages_owner_direction_idx
  on public.owner_email_center_messages(owner_user_id,direction,created_at desc);
create index if not exists owner_email_center_messages_in_reply_to_idx
  on public.owner_email_center_messages(in_reply_to)
  where in_reply_to is not null;

